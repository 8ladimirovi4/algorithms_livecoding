//Количество уникальных последовательностей букв из плиток

//Задание:
//У тебя есть n плиток, и на каждой плитке напечатана одна буква tiles[i].
//Найди количество возможных непустых последовательностей букв, 
// которые можно составить, используя буквы с этих плиток.

//Пример 1:

//Input: tiles = "AAB"
//Output: 8
//Explanation: The possible sequences are "A", "B", "AA", "AB", "BA", "AAB", "ABA", "BAA".

//Пример 2:
//Input: tiles = "AAABBC"
//Output: 188

//Пример 3:
//Input: tiles = "V"
//Output: 1

//Ограничения

//1 <= tiles.length <= 7:
//Длина строки tiles (то есть количество плиток) будет от 1 до 7


//Решение:

// Подсчитаем частоту букв, чтобы избежать генерации дубликатов.
// Рекурсивно строим последовательности, перебирая доступные буквы.
// Каждый раз уменьшаем частоту текущей буквы и добавляем её в последовательность.
// После рекурсии восстанавливаем частоту, чтобы учитывать другие варианты.

function numTilePossibilities(tiles) {
    // Проверяем, что длина tiles не превышает 7
    if (tiles.length < 1 || tiles.length > 7) {
        throw new Error("Длина строки tiles должна быть от 1 до 7.");
    }

    // Создаем объект, чтобы отслеживать количество каждой буквы
    const count = {};
    for (let char of tiles) {
        count[char] = (count[char] || 0) + 1;
    }

    let result = 0;
    
    // Рекурсивная функция для перебора всех возможных последовательностей
    function backtrack(count) {
        for (let char in count) {
            if (count[char] > 0) {
                // Добавляем эту букву в последовательность
                result++;
                // Уменьшаем количество этой буквы и вызываем рекурсию
                count[char]--;
                
                // Рекурсивно пытаемся добавить букву еще раз
                backtrack(count);
                
                // Восстанавливаем количество буквы
                count[char]++;
            }
        }
    }
    
    // Запускаем рекурсивную функцию
    backtrack(count);
    
    return result;
}

// Тестирование функции
console.log(numTilePossibilities("AAB")); // 8
console.log(numTilePossibilities("AAABBC")); // 188
console.log(numTilePossibilities("V")); // 1

